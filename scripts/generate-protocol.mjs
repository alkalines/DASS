// Intentionally small generator for the restricted signaling.rs wire declarations.
// Reject unsupported field types rather than silently generating an incorrect contract.
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync(new URL("../crates/protocol/src/signaling.rs", import.meta.url), "utf8");
const destination = new URL("../crates/protocol/generated/signaling.ts", import.meta.url);
const snakeCase = name => name.replace(/[A-Z]/g, (letter, index) => `${index ? "_" : ""}${letter.toLowerCase()}`);
const types = new Map([["String", "string"], ["bool", "boolean"], ["u8", "number"], ["u16", "number"], ["u32", "number"]]);
const names = [...source.matchAll(/pub (?:struct|enum) (\w+)/g)].map(match => match[1]);
for (const name of names) types.set(name, name);
const fields = text => text.split(",").map(field => field.trim().replace(/^pub /, "")).filter(Boolean).map(field => {
    const match = /^(\w+): (\w+)(?:<(\w+)>)?$/.exec(field);
    if (!match || (match[3] ? match[2] !== "Vec" || !types.has(match[3]) : !types.has(match[2]))) throw new Error(`Unsupported Rust field: ${field}`);
    return `${match[1]}: ${match[3] ? `Array<${types.get(match[3])}>` : types.get(match[2])}`;
}).join("; ");
let output = "// Generated by bun scripts/generate-protocol.mjs; do not edit.\n\n";
const discovery = readFileSync(new URL("../crates/protocol/src/lib.rs", import.meta.url), "utf8");
const version = /pub const PROTOCOL_VERSION: u16 = (\d+);/.exec(discovery);
if (!version) throw new Error("Missing protocol version");
output += `export const PROTOCOL_VERSION = ${version[1]};\n`;
for (const match of source.matchAll(/pub const (\w+): usize = ([\d_]+);/g)) {
    output += `export const ${match[1]} = ${match[2].replaceAll("_", "")};\n`;
}
for (const match of source.matchAll(/pub struct (\w+) \{([^}]+)\}/g)) {
    output += `\nexport type ${match[1]} = { ${fields(match[2])} };\n`;
}
for (const match of source.matchAll(/pub enum (\w+) \{([\s\S]*?)\n\}/g)) {
    const variants = [...match[2].matchAll(/(\w+)(?: \{([^}]+)\})?,/g)];
    const tagged = variants.some(variant => variant[2]);
    output += `\nexport type ${match[1]} =\n${variants.map(variant => tagged
        ? `    | { type: "${snakeCase(variant[1])}"; ${fields(variant[2] ?? "")} }`
        : `    | "${snakeCase(variant[1])}"`).join("\n")};\n`;
}
if (process.argv.includes("--check")) {
    if (readFileSync(destination, "utf8") !== output) throw new Error("Generated protocol is stale");
} else {
    writeFileSync(destination, output);
}
